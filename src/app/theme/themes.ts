const darkQuery =
  typeof window !== 'undefined' ? window.matchMedia('(prefers-color-scheme: dark)') : undefined;

/** Which slot the mode picks right now. */
export function activeSlot(appearance: Appearance): 'dark' | 'light' {
  const mode = appearance.mode ?? 'dark';
  if (mode === 'system') return darkQuery?.matches === false ? 'light' : 'dark';
  return mode;
}

/** The theme id the app should show for these settings. */
export function activeThemeId(appearance: Appearance): string {
  return activeSlot(appearance) === 'light'
    ? (appearance.lightTheme ?? 'normie')
    : appearance.theme;
}

let lastAppearance: Appearance | undefined;
// System mode follows the OS live.
darkQuery?.addEventListener('change', () => {
  if (lastAppearance?.mode === 'system') applyAppearance(lastAppearance);
});

export function availableThemes(appearance: Appearance): Theme[] {
  return [...themes, ...(appearance.customThemes ?? []).map((theme) => ({
    ...theme, tagline: 'Custom theme', origin: 'custom' as const,
  }))];
}

function paintTheme(id: string, appearance: Appearance): void {
  const theme = availableThemes(appearance).find((item) => item.id === id) ?? themes[0];
  const root = document.documentElement;
  for (const [token, value] of Object.entries(theme.tokens)) root.style.setProperty(token, value);
  root.style.colorScheme = theme.scheme;
  root.dataset.theme = theme.id;
  root.dataset.scheme = theme.scheme;
}

export function applyAppearance(appearance: Appearance): void {
  lastAppearance = appearance;
  paintTheme(activeThemeId(appearance), appearance);
  const root = document.documentElement;
  flamePalette.value =
    flamePalettes.find((item) => item.id === appearance.flame) ?? flamePalettes[0];
  const [deep, body, tips] = flamePalette.value.colors;
  root.style.setProperty('--flame-deep', deep);
  root.style.setProperty('--flame-body', body);
  root.style.setProperty('--flame-tips', tips);
}

/** "#rrggbb" → [r, g, b] in 0–1, for shader uniforms. */
export function rgb(hex: string): [number, number, number] {
  const value = Number.parseInt(hex.slice(1), 16);
  return [((value >> 16) & 255) / 255, ((value >> 8) & 255) / 255, (value & 255) / 255];
}
